// BUGFIX: `dict` is declared `as const` so every string field gets its own
// exact literal type (e.g. the German title is typed as the literal
// "Critical Path Scanner", not the general `string`). That means dict.de,
// dict.en, and dict.ar are each a DIFFERENT, mutually incompatible type,
// since their text differs. `Dict = typeof dict.de` then only accepted the
// German literal values specifically, so passing `t={t}` with the English
// or Arabic dictionary loaded (a real, everyday case, not an edge case)
// failed to type-check. This went undetected in earlier local checks and
// only surfaced in the real Vercel build. `Widen` strips every literal
// string down to the general `string` type, recursively through nested
// objects, so all three language dictionaries structurally satisfy `Dict`.
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? Widen<U>[]
    : T extends object
      ? { [K in keyof T]: Widen<T[K]> }
      : T

export type Dict = Widen<typeof dict.de>
